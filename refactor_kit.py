def main(argv):
    if "--list" in argv:
        for name, (sha, _b64) in FILES.items():
            print(f"{sha[:12]}  {name}")
        print(f"{len(FILES)} files")
        return 0
    out = (
        Path(argv[argv.index("--out") + 1])
        if "--out" in argv
        else Path("tests") / "refactor"
    )
    force = "--force" in argv
    written = skipped = 0
    for name, (sha, b64) in FILES.items():
        rel = Path(name)
        if rel.is_absolute() or ".." in rel.parts:
            print("refusing unsafe path:", name)
            return 1
        data = zlib.decompress(base64.b64decode("".join(b64)))
        if hashlib.sha256(data).hexdigest() != sha:
            print("CHECKSUM MISMATCH:", name)
            return 1
        dest = out / rel
        if dest.exists() and not force:
            skipped += 1
            continue
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(data)
        written += 1
    print(
        f"extracted {written} file(s) to {out}"
        + (
            f"; skipped {skipped} existing (use --force to overwrite)"
            if skipped
            else ""
        )
    )
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
